#!/usr/bin/env python3
"""Generate pc/glue/regmap.inc: libntr's display register variables with their DS I/O offsets.

libntr (PC) keeps every hardware register in its own variable (include/nitro/hw/X86/ioreg_*.h:
REG_<NAME>_OFFSET = DS offset from 0x04000000, REG_<NAME>_ADDR = &s_reg_<VAR>, reg_<VAR> = (*(REGTypeNNv *)...)).
The glue copies them into ntrgfx's register block at their DS addresses each frame.

usage: gen_regmap.py LIBNTR_DIR > pc/glue/regmap.inc
"""
import re
import sys

HEADERS = ["ioreg_GX.h", "ioreg_GXS.h", "ioreg_G2.h", "ioreg_G2S.h", "ioreg_G3X.h"]

def main():
    base = sys.argv[1] + "/include/nitro/hw/X86/"
    print("// Generated by pc/tools/gen_regmap.py from libntr's include/nitro/hw/X86 headers; do not edit.")
    print("// { DS I/O offset, size in bytes, libntr variable }")
    seen = set()
    for h in HEADERS:
        text = open(base + h).read()
        offsets = dict(re.findall(r"#define\s+REG_(\w+)_OFFSET\s+(0x[0-9a-fA-F]+)", text))
        addrs = dict(re.findall(r"#define\s+REG_(\w+)_ADDR\s+\(&(s_reg_\w+)\)", text))
        sizes = {}
        for bits, name in re.findall(r"\(\*\(\s*(?:const\s+)?REGType(\d+)v\s*\*\)\s*REG_(\w+)_ADDR\)", text):
            sizes[name] = int(bits) // 8
        for name, off in offsets.items():
            if name in addrs and name in sizes and addrs[name] not in seen:
                seen.add(addrs[name])
                print(f"{{ {off}, {sizes[name]}, &{addrs[name]} }},")

if __name__ == "__main__":
    main()
