CBattleAssist::CBattleAssist(CBattleAttackEffect **effects, CBattleAttackEffectData **effectData, BattleParamTable *params, u16 arg3)
{
    unk_04 = arg3;
    unk_08 = effects;
    unk_0C = effectData;
    unk_10 = params;
    unk_14 = CGame::GetInstance()->m_audioEngine;
}

CBattleAssist::~CBattleAssist()
{
}

CBattleAttackEffect *CBattleAssist::GetFreeEffect()
{
    for (int i = 0; i < 0x20; i++) {
        if (!unk_08[i]->HasData()) {
            return unk_08[i];
        }
    }
    return NULL;
}

extern "C" fx32 GetAssistTypeRate(int assistType, int type)
{
    return sAssistTypeRates[assistType][type];
}

extern "C" u16 GetAssistEffectTime(int assistType, int idx)
{
    return sAssistTimes[assistType][idx];
}
